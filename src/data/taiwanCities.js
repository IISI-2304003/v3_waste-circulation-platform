// 取得所有縣市名稱
export const getCities = () => {
  return taiwanCities.map((city) => city.name)
}

// 根據縣市取得區域（回傳物件包含 name, value, zipCode）
export const getDistricts = (cityName) => {
  const city = taiwanCities.find((c) => c.name === cityName)
  return city
    ? city.districts.map((district) => ({
        name: district.name,
        value: district.value,
        zipCode: district.zipCode || district.name.split(' ')[0],
      }))
    : []
}
